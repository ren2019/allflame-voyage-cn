  const rows = page.locator('.updates-list .update-title')
  await expect(rows.nth(0)).toHaveText('琪莎拉整程填充与漂流瓶译名')
  await expect(rows.nth(1)).toHaveText('琪莎拉优先保图并保护锚地材料')
  await expect(rows.nth(2)).toHaveText('仅突出特殊目的地')
  await expect(rows.nth(3)).toHaveText('精简海图库存卡片操作')
  await expect(rows.nth(4)).toHaveText('航程保护、库存纠错与补位')
  await expect(rows.nth(5)).toHaveText('提高锚地策略的蛤蜊目标提醒优先级')
  await expect(rows.nth(6)).toHaveText('兼容同类海图词缀措辞')
  await expect(rows.nth(7)).toHaveText('修复罪魂牢笼海图导入')
  await expect(rows.nth(8)).toHaveText('紧凑边界选择与通货图标')
  await expect(rows.nth(9)).toHaveText('逐步复制操作保持可见')
